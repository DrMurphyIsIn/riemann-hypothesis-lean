"""RK-2 C: emit the per-cell assembly theorem (KERNEL rational arithmetic + NAMED hypotheses), as rk1 lean/Assembly_*_L1.lean.

For a cell (K, L):  published <= Qinf  from
  * the two parity heads: KERNEL floors (PGC instance `floor`, given the ARB box hypotheses hbe/hbo), or, where no kernel floor
    exists, NAMED ARB hypotheses hAe/hAo : a * |x|^2 <= x^T A x with a = the Arb lambda_A lower bound rounded down;
  * hD : d <= lambda_D (ARB, certificate.json lambda_D, lower end rounded down);
  * hC : eps_C <= e (ARB, certificate.json eps_C, upper end rounded up);
  * hchain : Theorem RK (C1)-(C8) (PROVED in rk1/MEMO.md section 2; an abstract implication here).
Usage: asm_emit.py CELL_NAME CERT_DIR OUT.lean (kernel EVEN_JSON ODD_JSON | arb)        conjecture1_proved = False."""
import sys, json, math
from fractions import Fraction


def parse_ball(sv):
    t = sv.strip("[]").split("+/-")
    mid = Fraction(t[0].strip())
    rad = Fraction(t[1].strip()) if len(t) > 1 else Fraction(0)
    return mid, rad


def round_down(x, sig):
    e = math.floor(math.log10(x))
    q = Fraction(10) ** (e - sig + 1)
    return Fraction(math.floor(x / q)) * q


def round_up(x, sig):
    e = math.floor(math.log10(x))
    q = Fraction(10) ** (e - sig + 1)
    return Fraction(math.ceil(x / q)) * q


def lit(q):
    return f"(({q.numerator} : ℝ) / {q.denominator})"


def main():
    name, cdir, outp, mode = sys.argv[1:5]
    cert = json.load(open(f"{cdir}/certificate.json"))
    lmid, lrad = parse_ball(cert["lambda_D"])
    emid, erad = parse_ball(cert["eps_C"])
    d = round_down(lmid - lrad, 8)
    e = round_up(emid + erad, 3)
    hdr = []
    if mode == "kernel":
        je, jo = json.load(open(sys.argv[5])), json.load(open(sys.argv[6]))
        fe = Fraction(int(je["cS"]) - int(je["rho"]), 2 ** je["S_log2"])
        fo = Fraction(int(jo["cS"]) - int(jo["rho"]), 2 ** jo["S_log2"])
        ae, ao = round_down(fe, 7), round_down(fo, 7)
        a = min(ae, ao)
        me, mo = je["m"], jo["m"]
        trust = "KERNEL (PGC floors, given the ARB boxes hbe/hbo)"
    else:
        ce = json.load(open(f"{cdir}/chol_par0.json")); co = json.load(open(f"{cdir}/chol_par1.json"))
        le_, lo_ = parse_ball(ce["lambda_A_lower"]), parse_ball(co["lambda_A_lower"])
        ae, ao = round_down(le_[0] - le_[1], 7), round_down(lo_[0] - lo_[1], 7)
        a = min(ae, ao)
        me, mo = ce["m"], co["m"]
        trust = "NAMED ARB hypotheses hAe/hAo (verified Cholesky in rk1; no kernel floor in this round)"
    pub = round_down(min(a, d) - e, 6)
    assert pub > 0 and pub <= min(a, d) - e
    cellcert = parse_ball(cert["certificate"]["full_class_lower_bound"])
    rel = float(pub / (cellcert[0] - cellcert[1]))
    cdir_rel = cdir[cdir.find("rk1/"):] if "rk1/" in cdir else cdir
    out = []
    if mode == "kernel":
        out.append(f"import {je['name']}\nimport {jo['name']}\n\n")
    else:
        out.append("import Mathlib\n\n")
    out.append(f"/-! RK-2 C assembly `{name}` (generated by rk2/C/scripts/asm_emit.py from {cdir_rel}).\n"
               f"Heads: {trust}.  NAMED hypotheses (never asserted): hD = lambda_D >= {float(d):.8g} (ARB, certificate.json);\n"
               f"hC = eps_C <= {float(e):.3g} (ARB); hchain = {'Theorem RK′ (the signed self-dual version, rk1/MEMO.md section 2.2)' if 'EP5' in name else 'Theorem RK'} (C1)-(C8) (PROVED in rk1/MEMO.md section 2), an abstract\n"
               f"implication: any common floor a of the two head forms gives min(a, lambda_D) - eps_C <= Qinf, where Qinf stands for\n"
               f"inf R_K(g)/||g||^2 over complex g in C_c^inf(-L, L).  Lean asserts no unproved number.  conjecture1_proved = False. -/\n\n")
    out.append(f"set_option exponentiation.threshold 2048\n\nnamespace RK2.{name}\n\nopen RK2\n\n")
    hyps = []
    if mode == "kernel":
        hyps.append(f"    (hbe : ∀ i j : Fin {me}, |Aeven i j - (Mz {je['name']}.D i j : ℝ) / (2 : ℝ) ^ {je['S_log2']}| ≤ "
                    f"(({je['w']} : ℕ) : ℝ) / (2 : ℝ) ^ {je['S_log2']})\n")
        hyps.append(f"    (hbo : ∀ i j : Fin {mo}, |Aodd i j - (Mz {jo['name']}.D i j : ℝ) / (2 : ℝ) ^ {jo['S_log2']}| ≤ "
                    f"(({jo['w']} : ℕ) : ℝ) / (2 : ℝ) ^ {jo['S_log2']})\n")
    else:
        hyps.append(f"    (hAe : ∀ x : Fin {me} → ℝ, {lit(ae)} * ∑ i, x i ^ 2 ≤ ∑ i, ∑ j, x i * Aeven i j * x j)\n")
        hyps.append(f"    (hAo : ∀ x : Fin {mo} → ℝ, {lit(ao)} * ∑ i, x i ^ 2 ≤ ∑ i, ∑ j, x i * Aodd i j * x j)\n")
    out.append(f"theorem rk_floor (Aeven : Fin {me} → Fin {me} → ℝ) (Aodd : Fin {mo} → Fin {mo} → ℝ)\n" + "".join(hyps) +
               f"    (lamD epsC Qinf : ℝ) (hD : {lit(d)} ≤ lamD) (hC : epsC ≤ {lit(e)})\n"
               f"    (hchain : ∀ a : ℝ, (∀ x : Fin {me} → ℝ, a * ∑ i, x i ^ 2 ≤ ∑ i, ∑ j, x i * Aeven i j * x j) →\n"
               f"        (∀ x : Fin {mo} → ℝ, a * ∑ i, x i ^ 2 ≤ ∑ i, ∑ j, x i * Aodd i j * x j) → min a lamD - epsC ≤ Qinf) :\n"
               f"    {lit(pub)} ≤ Qinf := by\n")
    if mode == "kernel":
        for par, j, A, hb, aa in (("e", je, "Aeven", "hbe", a), ("o", jo, "Aodd", "hbo", a)):
            m = j["m"]
            out.append(f"  have ha{par} : ∀ x : Fin {m} → ℝ, {lit(aa)} * ∑ i, x i ^ 2 ≤ ∑ i, ∑ j, x i * {A} i j * x j := by\n"
                       f"    intro x\n"
                       f"    have hx : 0 ≤ ∑ i, x i ^ 2 := Finset.sum_nonneg (fun i _ => sq_nonneg (x i))\n"
                       f"    have hc : {lit(aa)} ≤ ((({j['cS']} : ℤ) - {j['rho']} : ℤ) : ℝ) / (2 : ℝ) ^ {j['S_log2']} := by norm_num\n"
                       f"    exact le_trans (mul_le_mul_of_nonneg_right hc hx) ({j['name']}.floor {A} {hb} x)\n")
    else:
        out.append(f"  have hae : ∀ x : Fin {me} → ℝ, {lit(a)} * ∑ i, x i ^ 2 ≤ ∑ i, ∑ j, x i * Aeven i j * x j := by\n"
                   f"    intro x\n"
                   f"    have hx : 0 ≤ ∑ i, x i ^ 2 := Finset.sum_nonneg (fun i _ => sq_nonneg (x i))\n"
                   f"    exact le_trans (mul_le_mul_of_nonneg_right (by norm_num) hx) (hAe x)\n"
                   f"  have hao : ∀ x : Fin {mo} → ℝ, {lit(a)} * ∑ i, x i ^ 2 ≤ ∑ i, ∑ j, x i * Aodd i j * x j := by\n"
                   f"    intro x\n"
                   f"    have hx : 0 ≤ ∑ i, x i ^ 2 := Finset.sum_nonneg (fun i _ => sq_nonneg (x i))\n"
                   f"    exact le_trans (mul_le_mul_of_nonneg_right (by norm_num) hx) (hAo x)\n")
    out.append(f"  have h := hchain _ hae hao\n"
               f"  have hmin : min {lit(a)} {lit(d)} ≤ min {lit(a)} lamD := min_le_min (le_refl _) hD\n"
               f"  have hnum : {lit(pub)} ≤ min {lit(a)} {lit(d)} - {lit(e)} := by norm_num\n"
               f"  linarith\n\nend RK2.{name}\n")
    open(outp, "w").write("".join(out))
    rep = dict(cell=name, mode=mode, a_even=float(ae), a_odd=float(ao), lambda_D_lower=float(d), eps_C_upper=float(e),
               published=float(pub), published_exact=str(pub), cert_full_class=cert["certificate"]["full_class_lower_bound"],
               published_rel_to_cert=rel)
    print(json.dumps(rep))


if __name__ == "__main__":
    main()
